-- Atualizar o total de cada pedido com base nos itens registrados.
update Pedido p
left join (
	select pedido_id, sum(quantidade * valor_cobrado) as total
	from Itens_Pedido
	group by pedido_id
) itens on itens.pedido_id = p.id
set p.valor_total = coalesce(itens.total, 0);

