-- Script de criacao e populacao de banco de dados de uma pizzaria
-- Comandos DDL para criar a estrutura do banco de dados
drop database if exists Pizzaria;
create database Pizzaria charset=UTF8 collate utf8_general_ci;
use Pizzaria;

create table Cliente(
	id integer primary key auto_increment,
	nome varchar(70) not null,
	cep varchar(20) not null,
	numero varchar(10),
	complemento varchar(30),
	referencia varchar(30)
);

create table Telefone(
	id integer primary key auto_increment,
	cliente_id integer not null,
	tipo ENUM('celular', 'residencial', 'comercial') not null default('celular'),
	numero varchar(15) not null,
	foreign key (cliente_id) references Cliente(id) on delete cascade
);

create table Pizza(
	id integer primary key auto_increment,
	nome varchar(30) not null,
	descricao varchar(200) not null,
	preco decimal(8,2) not null
);

create table Pedido(
	id integer primary key auto_increment,
	cliente_id integer not null,
	data datetime not null default(now()),
	valor_total decimal(8,2),
	foreign key (cliente_id) references Cliente(id)
);

create table Itens_Pedido(
	id integer primary key auto_increment,
	pedido_id integer,
	pizza_id integer not null,
	quantidade decimal(5,2) not null,
	valor_cobrado decimal(8,2) not null,
	foreign key (pedido_id) references Pedido(id) on delete cascade,
	foreign key (pizza_id) references Pizza(id)
);

show tables;
describe Cliente;
describe Telefone;
describe Pizza;
describe Pedido;
describe Itens_Pedido;

